/// 回答"哪些任务属于生活领域"。
///
/// 生活标记保存在**领域**上（`areas.is_life`），任务经
/// `tasks.project_id` → `projects.area_id` → `areas.is_life` 归属推导——这是用户
/// 决定的方案：不给任务加标记列，避免同一领域的任务各写一份可能互相矛盾的标记。
///
/// 此前没有任何代码读取该标记，两个消费方各自退化成别的判断：
/// `AnalyticsDao` 用领域名是否包含"生活/娱乐/休息/life"来猜，排程装配则根本不设置
/// `isLifeTask`，于是生活配额因子（`lifeQuota`）恒为 0、日历"生活"类别恒为空。
/// 名字匹配既漏（"家庭""健身"不算生活）又错（"生活服务业项目"会被算成生活），
/// 因此改为读真实的标记列。
///
/// 单独抽成端口而不是给 `TaskRepository` 加方法：它既不是任务事实，也不是领域维护，
/// 而是两者之间的关系查询，且排程与统计需要的正是这一个问题的答案。
abstract interface class LifeAreaLookup {
  /// 返回所有经项目归属到生活领域的任务 id。
  ///
  /// 没有项目的任务不属于任何领域，因此不会是生活任务。
  Future<Set<String>> lifeTaskIds();
}
